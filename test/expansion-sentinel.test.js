import assert from 'node:assert/strict';
import test from 'node:test';
import '../tools/headless.mjs';
import { HEROES, weaponsFor } from '../public/js/data/heroes.js';
import { SPR } from '../public/js/engine/sprites.js';
import { Game, strikeClip } from '../public/js/game/game.js';
import { defaultProfile, metaBonuses } from '../public/js/shared/profile.js';

test('the Sentinel earns shield bashes from connected Watchblade cuts and keeps manual crypt timing', () => {
  const g = new Game({ hero: 'sentinel', mode: 's15', meta: metaBonuses(defaultProfile()), crypts: false });
  const p = g.player, blade = g.mainWeapon();
  assert.equal(blade.id, 'sentinel_watchblade');
  assert.ok(!weaponsFor(HEROES.knight).includes(blade.id));
  assert.equal(p.armor, 2);
  p.face = 1;
  let clear = false;
  g.world.lineOfSight = () => clear;
  const spawn = x => g.spawnEnemy('zombie', p.x + x, p.y, { instant: true, always: true, hpMul: 1000 });
  const front = spawn(20), side = spawn(-27);
  g.grid.rebuild(g.enemies, p.x, p.y);
  const cut = () => { blade.cd = 0; blade.update(0); };
  cut();
  assert.equal(front.hp, front.maxHp);
  clear = true;
  cut();
  assert.ok(front.hp < front.maxHp);
  assert.equal(front.stunT, 0);
  cut();
  assert.equal(front.stunT, 0, 'the strike through the wall earned no charge');
  cut();
  assert.equal(front.stunT, blade.s.dur);
  assert.equal(side.hp, side.maxHp);

  for (let i = 1; i < 8; i++) blade.levelUp();
  g.addPassive('armor');
  assert.ok(g.evolvable().includes(blade));
  blade.evolve();
  assert.equal(g.mainWeapon().id, 'sentinel_last_bastion');
  front.stunT = 0;
  cut();
  assert.equal(front.stunT, 0);
  g.inCrypt = {};
  const hp = front.hp;
  blade.cd = 0;
  assert.ok(g.strike());
  const delay = strikeClip(SPR.sentinel).delay;
  assert.ok(delay > 0);
  blade.update(0, true);
  assert.equal(front.hp, hp);
  g.cryptTime += delay;
  blade.update(delay, true);
  assert.ok(front.hp < hp);
  assert.equal(front.stunT, blade.s.dur, 'the evolved shield is ready after one connected cut');
});
