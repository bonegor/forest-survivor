// Bake the Ylva costume on the same part renderer and grounded walk as the
// selected production Ranger. Only the standalone proposal is written.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { pathToFileURL } from 'node:url';
import { hexPack } from '../../public/js/engine/pixels.js';
import { PAL } from '../../public/js/art/palette.js';
import ranger from '../../public/assets/heroes-approved/archer.js';
import { APPROVED_HERO_ART } from '../../public/js/art/approved-heroes.js';
import { buildRangerWalk } from '../animation-round/ranger-walk.mjs';
import { trailHeadRows } from '../animation-round/trail-head.mjs';

const relative = path => new URL(path, import.meta.url);
const colors = {}, clips = {};
const approvedRanger=APPROVED_HERO_ART.archer.gen();
const approvedSteps=buildRangerWalk(ranger.palette,approvedRanger[ranger.idle[0]]).poses;
const rgb=c=>[c&255,c>>>8&255,c>>>16&255];
const faceTones=new Map();
function faceMark({hair,color}) {
  const [r,g,b]=rgb(color);
  if(hair) return g<25?'q':g<55?'7':g<88?'8':g<131?'9':g<175?'!':g<210?'?':'+';
  if(!faceTones.has(color)) {
    const token=String.fromCharCode(256+faceTones.size);
    colors[token]='#'+[r,g,b].map(v=>v.toString(16).padStart(2,'0')).join('');
    faceTones.set(color,token);
  }
  return faceTones.get(color);
}
const vikingHead=trailHeadRows.map(({x,pixels})=>({x:x+1-16,marks:pixels.map(faceMark).join('')}));
const context = vm.createContext({
  pal: entries => Object.assign(colors, entries),
  master: PAL, vikingHead, approvedSteps,
  ramps() {}, glow() {}, meta() {},
  anim: (id, box, draw) => { clips[id] = {box, draw}; },
});
for (const file of ['../art-v4/src/archer-b.px.js','ylva.px.js'])
  vm.runInContext(readFileSync(relative(file),'utf8'), context, { filename:file });

// Costume studies can use the exact original anatomy, face, palette and
// gait without copying those definitions or writing the baseline output.
const loadedCostumes = new Set();
export function loadWolfCostume(file) {
  if (!loadedCostumes.has(file)) {
    vm.runInContext(readFileSync(relative(file),'utf8'),context,{filename:file});
    loadedCostumes.add(file);
  }
  return { clips, colors };
}

function bakeOriginal() {
const {box,draw} = clips.ylva;
const palette = [0], ids = new Map();
const frames = Array.from({length:box.frames}, (_,frame) => {
  const image = Buffer.alloc(box.w*box.h);
  draw({frame,px(x,y,k) {
    if (!colors[k]) throw new Error('Unknown material '+k);
    const color = hexPack(colors[k]);
    if (!ids.has(color)) { ids.set(color,palette.length); palette.push(color); }
    image[y*box.w+x]=ids.get(color);
  }});
  // The sheet is mostly transparent margin. Store each run as [length,index]
  // and restore standard palette bytes once, when the proposal is imported.
  const runs = [];
  for (let p=0;p<image.length;) {
    const start=p++;
    while (p<image.length && image[p]===image[start] && p-start<255) p++;
    runs.push(p-start,image[start]);
  }
  return Buffer.from(runs).toString('base64');
});
if (palette.length>256) throw new Error('Ylva needs a wider palette index');
const sequence=(length,first=0)=>Array.from({length},(_,i)=>first+i);
const data={name:'Ylva Wolf-Tooth',pick:'review:ylva-wolf-tooth',w:box.w,h:box.h,anchorY:40,
  hires:1,fitW:36,fitH:34,attackRelease:3,attackFps:12,motionRate:APPROVED_HERO_ART.berserker.motionRate,idleRate:3.75,selfBob:true,
  indexBytes:1,palette,idle:sequence(8),walk:sequence(16,8),attack:sequence(6,24),
  attackWalk:sequence(6).map(k=>sequence(16,30+16*k))};
const baked = `// Generated by node tools/berserker-vikings/ylva-bake.mjs from ylva.px.js.
const data = ${JSON.stringify(data)};
const runs = ${JSON.stringify(frames)};
data.frames = runs.map(encoded => {
  const pairs = atob(encoded), pixels = new Uint8Array(data.w * data.h);
  let at = 0;
  for (let i=0; i<pairs.length; i+=2) {
    const end=at+pairs.charCodeAt(i);
    pixels.fill(pairs.charCodeAt(i+1),at,end);
    at=end;
  }
  return btoa(String.fromCharCode(...pixels));
});
export default data;
`;
writeFileSync(relative('ylva.js'),baked);
console.log('Ylva Wolf-Tooth:',frames.length,'native poses,',palette.length-1,'paint colors');
}

if (process.argv[1] && import.meta.url===pathToFileURL(process.argv[1]).href) bakeOriginal();
