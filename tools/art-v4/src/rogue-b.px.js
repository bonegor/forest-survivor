function draw(c){
 const F=new Map(),ph=(c.frame===0?0:c.frame-1)/8*Math.PI*2;
 const bob=[0,0,0,-1,-1,-1,0,0][c.frame===0?0:c.frame-1];
 const put=(x,y,k)=>{if(k&&k!=='.')F.set(Math.round(x)+','+Math.round(y),k)};
 const stamp=(x,y,rows)=>rows.forEach((r,j)=>[...r].forEach((k,i)=>put(x+i,y+j,k)));
 ORIGINAL[c.frame].forEach((r,y)=>[...r].forEach((k,x)=>{
  if(k==='.')return;
  // Keep precisely the original daggers, forearms and far flowing cape.
  if(y<7||y>27||(x>=17&&x<=28&&y<26))return;
  if(variant==='b'&&x<10&&y>15)return;
  put(x,y,k);
 }));
 // A continuous mantle fills the roots of the retained original wisps.
 for(let y=15;y<=30+bob;y++){
  const t=(y-15)/15,sway=Math.round(Math.sin(ph-t*2)*t);
  const left=Math.round((variant==='a'?14:16)-t*4)+sway;
  const right=Math.round(25+t*2)+sway;
  for(let x=left;x<=right;x++){
   const u=(x-left)/Math.max(1,right-left);
   put(x,y,x===left||x===right?'a':u<.16?'c':u<.32?'d':u<.46?'c':u<.62?'b':u<.77?'q':u<.9?'r':'p');
  }
 }
 // Two connected tapered cloth tails, no legs and no ground contact.
 const tail=(x0,y0,x1,y1,width,ramp)=>{
  const n=y1-y0;
  for(let y=y0;y<=y1;y++){
   const t=(y-y0)/n,cx=x0+(x1-x0)*t+Math.sin(ph+t*2)*t;
   const r=Math.max(.3,width*(1-t));
   for(let x=Math.round(cx-r);x<=Math.round(cx+r);x++)put(x,y,ramp[Math.min(ramp.length-1,Math.max(0,Math.round((x-cx+r)/(r*2||1)*(ramp.length-1))))]);
  }
 };
 if(variant==='a'){
  tail(20,26+bob,13,35+bob,6,'bdcbqrp');tail(25,27+bob,21,32+bob,2,'prsqp');
  stamp(14,15+bob,['..cdeedc......','.bcdeedcbcdcb.','bcdddcbbcdedcb','abbcbbaabbcba.']);
  stamp(17,6+bob,HOOD_A);
 }else{
  tail(21,26+bob,17,35+bob,6,'qsrcbap');tail(14,26+bob,10,31+bob,3,'bdeca');
  stamp(14,14+bob,['.eec.....edc..','deedc...dffdc.','cdedcb.cdeddcb','.bccbbqbbccba.','..bbqrrqbb....']);
  stamp(17,6+bob,HOOD_B);
 }
 // Original weapon arms overlay the cloak, keeping a visible grip on each dagger.
 ORIGINAL[c.frame].forEach((r,y)=>[...r].forEach((k,x)=>{
  if(y>=18&&y<=26&&((x>=28)||(x>=14&&x<=17))&&k!=='.')put(x,y,k);
 }));
 for(const [pos,k] of F){const [x,y]=pos.split(',').map(Number);if(x>=0&&x<40&&y>=0&&y<38)c.px(x,y,k)}
}
