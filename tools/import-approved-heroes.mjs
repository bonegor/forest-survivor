// Rebuild the shipped assets from the approved local animation reviewer.
// Start its comparator on port 3014, then run node tools/import-approved-heroes.mjs.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { APPROVED_DESIGNS } from '../public/js/expansion/roster.js';
import { readPng } from './png.mjs';

const sourceRoot = fileURLToPath(new URL('../example sprites folder/', import.meta.url));
const dest = fileURLToPath(new URL('../public/assets/heroes-approved/', import.meta.url));
const response = await fetch('http://127.0.0.1:3014/api/heroes-animation');
if (!response.ok) throw Error(`Could not read reviewer: ${response.status}`);
const { units } = await response.json();
const motions = ['idle', 'walk', 'attack'];

function complete(run) {
  const m = run?.metadata;
  return run?.nativeSheet && m?.frameIndexStatus === 'indexed' &&
    m.frameRects?.length === m.frameCount &&
    motions.every(k => m.animations?.[k]?.length &&
      m.animations[k].every(i => Number.isInteger(i) && i >= 0 && i < m.frameCount) &&
      run.previewTiming?.[k] > 0);
}

function packFrame(sheet, rect, palette, colors) {
  const [x, y, w, h] = rect;
  if (x < 0 || y < 0 || x + w > sheet.w || y + h > sheet.h) throw Error('Frame outside sheet');
  let left = w, top = h, right = 0, bottom = 0;
  for (let iy = 0; iy < h; iy++) {
    for (let ix = 0; ix < w; ix++) {
      if (!(sheet.d[(y + iy) * sheet.w + x + ix] >>> 24)) continue;
      left = Math.min(left, ix);
      right = Math.max(right, ix + 1);
      top = Math.min(top, iy);
      bottom = Math.max(bottom, iy + 1);
    }
  }
  const width = right - left, height = bottom - top;
  if (width <= 0 || height <= 0) throw Error('Blank frame');
  const indices = [];
  for (let iy = top; iy < bottom; iy++) {
    for (let ix = left; ix < right; ix++) {
      const pixel = sheet.d[(y + iy) * sheet.w + x + ix];
      const color = pixel >>> 24 ? pixel : 0;
      if (!colors.has(color)) {
        colors.set(color, palette.length);
        palette.push(color);
      }
      indices.push(colors.get(color));
    }
  }
  return { left, top, width, height, indices };
}

function pack(unit, run) {
  const m = run.metadata, source = join(sourceRoot, run.nativeSheet.slice(1));
  const sha256 = createHash('sha256').update(readFileSync(source)).digest('hex');
  if (m.native?.sha256 && sha256 !== m.native.sha256) throw Error(`Sheet hash changed: ${unit.id}`);
  if (m.anchorX * 2 !== m.w || m.anchorY < 0 || m.anchorY >= m.h ||
      !Number.isInteger(m.attackRelease) || m.attackRelease < 0 || m.attackRelease >= m.animations.attack.length) {
    throw Error(`Invalid registration: ${unit.id}`);
  }
  const sheet = readPng(source), palette = [0], colors = new Map([[0, 0]]);
  const frames = m.frameRects.map(rect => {
    if (rect[2] !== m.w || rect[3] !== m.h) throw Error(`Unequal frame sizes: ${unit.id}`);
    return packFrame(sheet, rect, palette, colors);
  });
  const indexBytes = palette.length <= 256 ? 1 : 2;
  return {
    design: unit.id, source: run.nativeSheet, sha256,
    w: m.w, h: m.h, anchorY: m.anchorY,
    ...m.animations, attackRelease: m.attackRelease, attackFps: run.previewTiming.attack,
    walkFps: run.previewTiming.walk, idleFps: run.previewTiming.idle,
    floating: !!m.floating, palette, indexBytes,
    frames: frames.map(({ left, top, width, height, indices }) => {
      const data = Buffer.alloc(indices.length * indexBytes);
      indices.forEach((index, i) => data.writeUIntLE(index, i * indexBytes, indexBytes));
      return [left, top, width, height, data.toString('base64')];
    }),
  };
}

const sheets = Object.entries(APPROVED_DESIGNS).map(([id, design]) => {
  const unit = units.find(u => u.id === design);
  if (!unit) throw Error(`Missing approved design: ${design}`);
  const run = [...unit.polishes].reverse().concat(unit.iteration2, unit.iteration1).find(complete);
  if (!run) throw Error(`No complete indexed clip: ${design}`);
  return [id, pack(unit, run)];
});
mkdirSync(dest, { recursive: true });
for (const [id, data] of sheets) {
  writeFileSync(join(dest, `${id}.js`), `// Generated by tools/import-approved-heroes.mjs.\nexport default ${JSON.stringify(data)};\n`);
}
const imports = sheets.map(([id]) => `import ${id} from './${id}.js';`);
const ids = sheets.map(([id]) => id);
writeFileSync(join(dest, 'index.js'), `// Generated by tools/import-approved-heroes.mjs.\n${imports.join('\n')}\n\nexport default { ${ids.join(', ')} };\n`);
console.log(`Imported ${sheets.length} approved native sheets`);
