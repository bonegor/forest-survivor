const designs = { crown, rune, lantern, aster, crescent, spire, scarab };
const families = new Map();
export function gemArt(familyId, rank) {
  if (familyId === DEFAULT_GEM_FAMILY) return defaultGem(rank);
  if (!families.has(familyId)) families.set(familyId, []);
  const sprites = families.get(familyId);
  return sprites[rank] ??= familyId === 'original'
    ? buildSprite('gem' + (rank + 1), originalGems['gem' + (rank + 1)])
    : buildGemArt(designs[familyId][rank], rank);
}

export function applyGemFamily(game, familyId) {
  game.gemArt = rank => gemArt(familyId, rank);
  for (const pickup of game.pickups) {
    if (pickup.kind === 'gem') pickup.setLook();
  }
}
