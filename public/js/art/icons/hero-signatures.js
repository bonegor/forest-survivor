// The 14px inventory cuts use the same one-pixel outline as the other items.
// An evolution keeps its original tool and adds a physical fitting or crest.
const icons = {};

function pair(base, evolution, drawing, fittings) {
  const rows = drawing.trim().split(/\s+/).map(row => row.padEnd(14, '.'));
  const evolved = rows.map(row => [...row]);
  for (const [x, y, brush] of fittings) {
    for (const [i, colour] of [...brush].entries()) evolved[y][x + i] = colour;
  }
  icons['i_' + base] = { frames: [rows] };
  icons['i_' + evolution] = { frames: [evolved.map(row => row.join(''))] };
}

